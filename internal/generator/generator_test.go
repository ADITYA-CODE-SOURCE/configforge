func TestGeneratedGoCompiles(t *testing.T) {
	manifests, err := manifest.LoadDir(filepath.Join("..", "..", "manifests"))
	if err != nil {
		t.Fatalf("LoadDir: %v", err)
	}

	got := GenerateDefaults(manifests)
	if !bytes.Contains(got, []byte("Code generated by ConfigForge. DO NOT EDIT.")) {
		t.Fatal("missing DO NOT EDIT header")
	}
	if !bytes.Contains(got, []byte(`var EnvMetadata`)) {
		t.Fatal("missing EnvMetadata variable")
	}
	if !bytes.Contains(got, []byte(`var ManifestDefaults`)) {
		t.Fatal("missing ManifestDefaults variable")
	}
}
